export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductById(id: string): Product | undefined {
  return products.find((p) => p.id === id);
}

export function getProductsByVendor(vendorId: string): Product[] {
  return products.filter((p) => p.vendorId === vendorId);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return products.filter((p) => p.categorySlug === categorySlug);
}

export function getFeaturedProducts(): Product[] {
  return products.filter((p) => p.featured && p.status === "active");
}

export function getTrendingProducts(): Product[] {
  return products.filter((p) => p.trending && p.status === "active");
}

export function getBestSellingProducts(): Product[] {
  return products.filter((p) => p.bestSelling && p.status === "active");
}

export function getFlashSaleProducts(): Product[] {
  return products.filter((p) => p.flashSale && p.status === "active");
}

export function getNewArrivals(): Product[] {
  return [...products]
    .filter((p) => p.status === "active")
    .sort((a, b) => new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime())
    .slice(0, 8);
}

export function getRelatedProducts(product: Product, limit = 8): Product[] {
  return products
    .filter(
      (p) =>
        p.id !== product.id &&
        p.status === "active" &&
        (p.categorySlug === product.categorySlug ||
          p.vendorId === product.vendorId ||
          p.tags.some((t) => product.tags.includes(t)))
    )
    .slice(0, limit);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.status === "active" &&
      (p.name.toLowerCase().includes(q) ||
        p.description.toLowerCase().includes(q) ||
        p.category.toLowerCase().includes(q) ||
        p.brand.toLowerCase().includes(q) ||
        p.tags.some((t) => t.toLowerCase().includes(q)) ||
        p.vendorName.toLowerCase().includes(q))
  );
}

export function getProductBrands(): string[] {
  return [...new Set(products.map((p) => p.brand))].sort();
}
